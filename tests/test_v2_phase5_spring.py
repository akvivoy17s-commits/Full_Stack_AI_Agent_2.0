@pytest.mark.skipif(not shutil.which("javac"), reason="no JDK")
@pytest.mark.parametrize("db", ["sqlite", "mongodb", "none"])
def test_generated_java_has_no_syntax_errors(db):
    """javac without the Spring jars: every error must be a missing-symbol/package one, never a syntax error."""
    spec, st, m, files = sb(db)
    with tempfile.TemporaryDirectory() as d:
        srcs = []
        for rel, text in files.items():
            if rel.endswith(".java"):
                p = Path(d, rel); p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text); srcs.append(str(p))
        r = subprocess.run(["javac", "-proc:none", "-d", d + "/out", *srcs], capture_output=True, text=True)
        bad = [l for l in r.stderr.splitlines() if "error:" in l and not re.search(r"does not exist|cannot find symbol|static import only|cannot access|bad class file|package .* not|is not abstract|incompatible types|method does not override", l)]
        assert not bad, bad[:5]
