    spec, st, m, files = sb(db)
    n = " ".join(files)
    assert ("AuthController" in n) == m["auth"] and ("JwtAuth" in n) == m["auth"] and ("AnonymousAuth" in n) == (not m["auth"] and db != "none")
    assert ("SeedRunner" in n) == (db != "none") and ("AuthFlowTest" in n) == (db == "sqlite")
    assert ("spring-security-crypto" in files["backend/pom.xml"]) == m["auth"]
    sj = files["backend/src/main/resources/schema.json"]
    assert ('"seed"' in sj) and (m["auth"] == ("JWT_SECRET" in files["backend/.env.example"]))


