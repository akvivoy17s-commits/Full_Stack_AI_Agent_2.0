def _tables(sql):
    return re.findall(r'CREATE TABLE [`\["]?(\w+)', sql)


def test_sqlite_script_really_runs_and_enforces_rules():
    spec, st, m, files = sb("sqlite")
    sql = files["backend/src/main/resources/db/migration/V1__initial.sql"]
    con = sqlite3.connect(":memory:")
    con.execute("PRAGMA foreign_keys=ON")
    con.executescript(sql)
    assert set(_tables(sql)) == {e["table"] for e in m["entities"]}
    assert con.execute("PRAGMA foreign_key_check").fetchall() == []
    fks = sum(len(con.execute(f'PRAGMA foreign_key_list("{e["table"]}")').fetchall()) for e in m["entities"])
    assert fks == sum(1 for e in m["entities"] for f in e["fields"] if f["type"] == "ref" and f.get("fk"))
    idx = {r[0] for r in con.execute("select name from sqlite_master where type='index' and name like 'ix_%'")}
    assert idx == {f"ix_{e['table']}_{f['name']}"[:200] for e in m["entities"] for f in e["fields"] if f.get("index")}


@pytest.mark.parametrize("db", ["postgresql", "mysql", "mssql"])
def test_dialect_rules(db):
    spec, st, m, files = sb(db)
    sql = files["backend/src/main/resources/db/migration/V1__initial.sql"]
    assert set(_tables(sql)) == {e["table"] for e in m["entities"]}
    assert sql.count("CREATE TABLE") == len(m["entities"]) and "AUTOINCREMENT" not in sql
    if db == "mssql":
        assert "IDENTITY(1,1)" in sql and "RESTRICT" not in sql and "SET NULL" not in sql and "NVARCHAR" in sql
    if db == "mysql":
        assert "AUTO_INCREMENT" in sql and "ENGINE=InnoDB" in sql and "`id`" in sql
    if db == "postgresql":
        assert "GENERATED BY DEFAULT AS IDENTITY" in sql and "TIMESTAMP" in sql
    parents = [t for t in _tables(sql)]
    for ref in re.findall(r"REFERENCES [`\[\"](\w+)", sql):          # a parent table is always created before the table that refers to it
        assert ref in parents


