# ------------------------------------------------------------------ compatibility rules
def bad(**kw):
    errs, _ = rules.validate(kw)
    return {f for e in errs for f in e["fields"]}


def test_incompatible_combinations_are_detected():
    assert {"backend", "database"} <= bad(frontend="react", frontend_lang="ts", backend="django", database="mongodb")
    assert {"frontend", "frontend_lang"} <= bad(frontend="html", frontend_lang="ts")
    assert {"frontend_lang"} <= bad(frontend="angular", frontend_lang="js")
    assert {"database", "backend"} <= bad(frontend="react", backend="none", database="postgresql")
    assert {"auth", "backend"} <= bad(frontend="react", backend="none", auth="jwt")
    assert {"auth", "database"} <= bad(frontend="react", backend="express", database="none", auth="jwt")
    assert {"deploy", "frontend"} <= bad(frontend="next", deploy="static")
    assert {"ai", "backend"} <= bad(frontend="react", backend="express", ai="python-inprocess")
    assert {"testing", "frontend"} <= bad(frontend="react", testing="karma")
    assert {"orm"} <= bad(frontend="react", backend="express", database="postgresql", orm="typeorm")
    assert bad(frontend="react", backend="express", database="redis-db") == {"database"}


def test_valid_combinations_pass_and_warn_where_expected():
    errs, warns = rules.validate({"frontend": "react", "frontend_lang": "ts", "backend": "express", "backend_lang": "ts", "database": "postgresql",
                                  "orm": "knex", "auth": "jwt", "deploy": "vercel"})
    assert not errs and any("hosts the frontend only" in w["msg"] for w in warns)


