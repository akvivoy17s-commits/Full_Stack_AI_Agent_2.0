def test_options_are_filtered_by_the_current_selection():
    opts = rules.options({"frontend": "react", "frontend_lang": "ts", "backend": "django", "database": "postgresql"})
    mongo = next(o for o in opts["database"] if o["id"] == "mongodb")
    assert not mongo["allowed"] and "MongoDB" in mongo["why_not"]
    assert next(o for o in opts["database"] if o["id"] == "mysql")["allowed"]
    html = rules.options({"frontend": "html", "frontend_lang": "js"})
    assert not next(o for o in html["frontend_lang"] if o["id"] == "ts")["allowed"]


