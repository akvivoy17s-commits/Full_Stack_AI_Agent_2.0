# ------------------------------------------------------------------ fuzz: the engine never overrides or contradicts user choices
NEUTRAL_BRIEFS = [
    "Portfolio website for a photographer",
    "SaaS analytics dashboard with login, billing and file uploads",
    "Online store with cart, checkout and an admin panel",
    "Real-time chat application with user accounts",
    "AI chatbot assistant with image classification",
    "Enterprise hospital management system with roles",
    "Blog CMS with image upload and email notifications",
    "Team notes app with Firebase authentication",
]


def _compatible_triples():
    for fe, be, db in itertools.product([k for k in C.FRONTEND], [k for k in C.BACKEND], [k for k in C.DATABASE]):
        lang = "ts" if "ts" in C.FRONTEND[fe]["langs"] else "js"
        errs, _ = rules.validate({"frontend": fe, "frontend_lang": lang, "backend": be, "database": db})
        if not errs:
            yield {"frontend": fe, "backend": be, "database": db}


def test_fuzz_hybrid_preserves_user_choices_and_stays_valid():
    triples, runs = 0, 0
    for t in _compatible_triples():
        triples += 1
        for n in (1, 2, 3):
            for keys in itertools.combinations(t, n):
                prefs = {k: t[k] for k in keys}
                for brief in NEUTRAL_BRIEFS:
                    r = resolve("hybrid", prefs, brief)
                    runs += 1
                    assert r["ok"], (prefs, brief, r["errors"])
                    assert all(r["stack"][k] == v and r["sources"][k] == "user" for k, v in prefs.items()), (prefs, brief)
    assert triples > 300 and runs > 10000
